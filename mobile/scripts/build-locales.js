const fs = require('node:fs');
const path = require('node:path');
const localeRoot = path.resolve(__dirname, '../locales');

function loadCatalogs() {
  return Object.fromEntries(['en', 'zh-CN'].map(locale => [locale, JSON.parse(fs.readFileSync(path.join(localeRoot, `${locale}.json`), 'utf8'))]));
}
function validateCatalogs(catalogs) {
  const errors = [];
  const params = text => [...new Set([...text.matchAll(/\{([a-zA-Z][\w]*)\}/g)].map(match => match[1]))].sort().join(',');
  const keys = [...new Set(['en', 'zh-CN'].flatMap(locale => Object.keys(catalogs[locale] || {})))].sort();
  for (const key of keys) {
    const variants = {};
    for (const locale of ['en', 'zh-CN']) {
      const value = catalogs[locale]?.[key];
      if (typeof value === 'string') variants[locale] = {text:value};
      else if (value && typeof value === 'object' && !Array.isArray(value) && Object.keys(value).sort().join(',') === 'one,other') variants[locale] = value;
      else { errors.push(`${locale}:${key}: missing or invalid message`); continue; }
      for (const [variant, text] of Object.entries(variants[locale])) if (typeof text !== 'string' || !text.trim()) errors.push(`${locale}:${key}.${variant}: empty message`);
    }
    if (!variants.en || !variants['zh-CN']) continue;
    if (Object.keys(variants.en).join(',') !== Object.keys(variants['zh-CN']).join(',')) errors.push(`${key}: variant mismatch`);
    for (const [variant, text] of Object.entries(variants.en)) {
      const translated = variants['zh-CN'][variant];
      if (typeof text === 'string' && typeof translated === 'string' && params(text) !== params(translated)) errors.push(`${key}.${variant}: parameter mismatch`);
    }
  }
  if (!keys.length) errors.push('No messages');
  return errors;
}
function serializeMessages(catalogs) {
  const ordered = Object.fromEntries(['en','zh-CN'].map(locale => [locale, Object.fromEntries(Object.keys(catalogs[locale]).sort().map(key => [key, catalogs[locale][key]]))]));
  return `// Generated by mobile/scripts/build-locales.js. Edit the JSON catalogs only.\n(function(root, factory) {\n  const messages = factory();\n  if (typeof module === 'object' && module.exports) module.exports = messages;\n  if (root) root.TrackMessages = messages;\n})(typeof globalThis !== 'undefined' ? globalThis : this, function() {\n  return ${JSON.stringify(ordered, null, 2)};\n});\n`;
}
if (require.main === module) {
  try {
    const catalogs = loadCatalogs();
    const errors = validateCatalogs(catalogs);
    if (errors.length) throw new Error(errors.join('\n'));
    const output = serializeMessages(catalogs);
    const target = path.join(localeRoot, 'messages.js');
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('messages.js is stale; run node mobile/scripts/build-locales.js');
      console.log('Locale catalogs and generated messages are current.');
    } else { fs.writeFileSync(target, output); console.log('Generated mobile/locales/messages.js'); }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = {loadCatalogs, validateCatalogs, serializeMessages};
